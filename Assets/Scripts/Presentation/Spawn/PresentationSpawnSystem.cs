                _outcroppingPrefabs[i] = Resources.Load<GameObject>(VeilstoneOutcroppingPrefabPaths[i]);
        }

        var prefab = _outcroppingPrefabs[Mathf.Abs(entity.Index) % _outcroppingPrefabs.Length];
        if (prefab == null) return null;

